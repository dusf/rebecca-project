  /* ==================== 语言名称映射 ==================== */
  var LOCALE_NAMES = {
    'zh-CN': '中文',
    'en-US': 'English',
    'fr-FR': 'Français'
  };

  /* ==================== 核心 API ==================== */

  function getLocale() {
    var country = getCountry();
    var countryInfo = COUNTRIES[country];
    return countryInfo ? countryInfo.locale : 'zh-CN';
  }

  function setLocale(locale) {
    // 找到对应的国家代码
    var countryCode = null;
    Object.keys(COUNTRIES).forEach(function (code) {
      if (COUNTRIES[code].locale === locale) {
        countryCode = code;
      }
    });
    if (countryCode) {
      setCountry(countryCode);
    }
  }

  function t(key) {
    var locale = getLocale();
    var dict = DICT[locale];
    return dict[key] || DICT['zh-CN'][key] || key;
  }

  /** 替换所有带 data-i18n 属性的元素文本 */
  function applyAll() {
    var els = document.querySelectorAll('[data-i18n]');
    els.forEach(function (el) {
      var key = el.getAttribute('data-i18n');
      var text = t(key);
      // 处理换行：\n → <br>
      if (text.indexOf('\n') !== -1) {
        el.innerHTML = text.split('\n').map(function (line) {
          return line.replace(/</g, '&lt;').replace(/>/g, '&gt;');
        }).join('<br>');
      } else {
        el.textContent = text;
      }
    });
    // placeholder
    var phEls = document.querySelectorAll('[data-i18n-placeholder]');
    phEls.forEach(function (el) {
      el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });
    // html lang
    document.documentElement.lang = getLocale();
  }

  function getSupported() {
    var locales = [];
    Object.keys(COUNTRIES).forEach(function (code) {
      locales.push(COUNTRIES[code].locale);
    });
    return locales;
  }
  function getLocaleName(locale) { return LOCALE_NAMES[locale] || locale; }

  /* ==================== 导出 ==================== */
  window.ShopI18n = {
    t: t,
    getLocale: getLocale,
    setLocale: setLocale,
    getSupported: getSupported,
    getLocaleName: getLocaleName,
    applyAll: applyAll,
    // 国家相关
    getCountry: getCountry,
    setCountry: setCountry,
    getCountryInfo: getCountryInfo,
    getCountries: getCountries
  };

